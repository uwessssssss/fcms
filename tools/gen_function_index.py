#!/usr/bin/env python3
"""
gen_function_index -- which migration holds the LIVE definition of every
function and view, and how many times each was rewritten.

Migrations are append-only: a fix re-issues a whole function in a new file, so
fn_close_shift exists in ten files and only the last one runs. Reading an old
copy is how a fix gets made to dead code. This writes docs/LIVE-FUNCTIONS.md;
`--check` (run by verify.sh) fails if that file is out of date.
"""
import re, sys, pathlib
ROOT = pathlib.Path(__file__).resolve().parents[1]
MIG = ROOT / 'db' / 'migrations'
order = [l.split()[0] for l in (ROOT / 'db' / 'migrate.sh').read_text(encoding='utf-8').splitlines()
         if re.match(r"\s+\d{3}_\w+\.sql", l)]
defs = {}
for name in order:
    s = re.sub(r"--[^\n]*", "", (MIG / name).read_text(encoding='utf-8'))
    for m in re.finditer(r"CREATE OR REPLACE (FUNCTION|VIEW) (\w+)", s):
        defs.setdefault((m.group(2), m.group(1)), []).append(name)
rows = sorted(defs.items(), key=lambda kv: (-len(kv[1]), kv[0][0]))
out = ["# Live functions and views", "",
       "Generated by `tools/gen_function_index.py` -- do not edit by hand.", "",
       "Migrations never change: a fix re-issues the whole function in a new file. **Only the",
       "file in the *live in* column runs.** Change that one -- by adding a new migration that",
       "copies it -- never an older copy.", "",
       "| name | kind | live in | times written |", "|---|---|---|---|"]
for (name, kind), files in rows:
    out.append(f"| `{name}` | {kind.lower()} | `{files[-1]}` | {len(files)} |")
text = "\n".join(out) + "\n"
target = ROOT / 'docs' / 'LIVE-FUNCTIONS.md'
if '--check' in sys.argv:
    if not target.exists() or target.read_text(encoding='utf-8') != text:
        print("  X docs/LIVE-FUNCTIONS.md is out of date: run python3 tools/gen_function_index.py"); sys.exit(1)
    print(f"function index current: {len(rows)} functions and views"); sys.exit(0)
target.write_text(text, encoding='utf-8')
print(f"wrote docs/LIVE-FUNCTIONS.md: {len(rows)} functions and views")
